# SQLite / PostgreSQL adapter. Requires psycopg[binary] for PostgreSQL.
import os, sqlite3, re, secrets, hashlib
from contextlib import contextmanager

USING_POSTGRES=bool(os.environ.get('DATABASE_URL'))

class Row:
    def __init__(self, values, columns):
        self.values=tuple(values); self.mapping=dict(zip(columns,self.values))
    def __getitem__(self,key):
        return self.values[key] if isinstance(key,int) else self.mapping[key]
    def keys(self): return self.mapping.keys()
    def __iter__(self): return iter(self.values)

class Cursor:
    def __init__(self, cursor): self.cursor=cursor
    def fetchone(self):
        r=self.cursor.fetchone()
        return Row(r,[d.name for d in self.cursor.description]) if r is not None else None
    def fetchall(self):
        columns=[d.name for d in self.cursor.description]
        return [Row(r,columns) for r in self.cursor.fetchall()]

class PgConnection:
    def __init__(self,conn): self.conn=conn
    def execute(self,query,params=()):
        q=query.strip()
        if q.upper().startswith('PRAGMA TABLE_INFO'):
            return self.conn.execute("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='messages' ORDER BY ordinal_position")
        if re.search(r'INSERT\s+OR\s+IGNORE',q,re.I):
            q=re.sub(r'INSERT\s+OR\s+IGNORE','INSERT',q,flags=re.I)
            q += ' ON CONFLICT DO NOTHING'
        if re.search(r'INSERT\s+OR\s+REPLACE',q,re.I):
            q=re.sub(r'INSERT\s+OR\s+REPLACE','INSERT',q,flags=re.I)
            table=re.search(r'INSERT\s+INTO\s+(\w+)',q,re.I).group(1).lower()
            mapping={'blocks':('user_id',['reason','at']),'access':('user_id',['active','added_at']),'group_locks':('chat_id',['prior_permissions','locked_at'])}
            if table not in mapping: raise ValueError('Unsupported REPLACE table: '+table)
            key,columns=mapping[table]
            q+=f' ON CONFLICT ({key}) DO UPDATE SET '+','.join(f'{c}=EXCLUDED.{c}' for c in columns)
        q=q.replace('?', '%s')
        return Cursor(self.conn.execute(q,params))
    def executescript(self,script):
        for q in script.split(';'):
            if q.strip(): self.execute(q)
    def commit(self): self.conn.commit()
    def close(self): self.conn.close()

@contextmanager
def db():
    if USING_POSTGRES:
        import psycopg
        conn=psycopg.connect(os.environ['DATABASE_URL'],connect_timeout=10)
        wrapper=PgConnection(conn)
    else:
        conn=sqlite3.connect(os.environ.get('MINIAPP_DB','miniapp.db'),timeout=15)
        conn.row_factory=sqlite3.Row
        wrapper=conn
    try:
        yield wrapper
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        conn.close()

SCHEMA='''
CREATE TABLE IF NOT EXISTS access(user_id BIGINT PRIMARY KEY, active INTEGER NOT NULL DEFAULT 1, added_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS blocks(user_id BIGINT PRIMARY KEY, reason TEXT, at BIGINT);
CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, action TEXT, at BIGINT);
CREATE TABLE IF NOT EXISTS groups(chat_id BIGINT PRIMARY KEY, title TEXT NOT NULL, members BIGINT DEFAULT 0, updated BIGINT);
CREATE TABLE IF NOT EXISTS messages(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, chat_id BIGINT NOT NULL, message_id BIGINT, sender TEXT, text TEXT, at BIGINT, sender_id BIGINT, UNIQUE(chat_id,message_id));
CREATE INDEX IF NOT EXISTS msg_chat ON messages(chat_id,id);
CREATE TABLE IF NOT EXISTS settings(k TEXT PRIMARY KEY,v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS activity(chat_id BIGINT,user_id BIGINT,display_name TEXT,at BIGINT,PRIMARY KEY(chat_id,user_id));
CREATE TABLE IF NOT EXISTS membership_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,chat_id BIGINT,kind TEXT,at BIGINT);
CREATE TABLE IF NOT EXISTS ai_history(user_id BIGINT,seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,role TEXT,content TEXT,at BIGINT);
CREATE TABLE IF NOT EXISTS group_locks(chat_id BIGINT PRIMARY KEY, prior_permissions TEXT NOT NULL, locked_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS bridge_receipts(event_id TEXT PRIMARY KEY, received_at BIGINT NOT NULL);
'''
SQLITE_SCHEMA=SCHEMA.replace('BIGINT GENERATED BY DEFAULT AS IDENTITY','INTEGER').replace('BIGINT','INTEGER')
# SQLite INTEGER PRIMARY KEY automatically increments; no need AUTOINCREMENT.

def initialize_database(path,password):
    with db() as c:
        c.executescript(SCHEMA if USING_POSTGRES else SQLITE_SCHEMA)
        if USING_POSTGRES:
            cols={r[0] for r in c.execute("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='messages'").fetchall()}
        else:
            cols={r[1] for r in c.execute('PRAGMA table_info(messages)').fetchall()}
        if 'sender_id' not in cols: c.execute('ALTER TABLE messages ADD COLUMN sender_id BIGINT')
        if not c.execute("SELECT 1 FROM settings WHERE k='password_salt'").fetchone():
            salt=secrets.token_hex(16)
            digest=hashlib.pbkdf2_hmac('sha256',password.encode(),bytes.fromhex(salt),240000).hex()
            c.execute("INSERT INTO settings VALUES ('password_salt',?)",(salt,))
            c.execute("INSERT INTO settings VALUES ('password_hash',?)",(digest,))
            c.execute("INSERT INTO settings VALUES ('password_epoch','1')")
